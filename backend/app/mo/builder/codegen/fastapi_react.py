def generate(spec: ProjectSpec) -> list[GeneratedFile]:
    """Produce every source file for the project. Raises GenerationError on a bad template."""
    files: list[GeneratedFile] = []
    for model in spec.models:
        files.append(_model_file(model))
        files.append(_schema_file(model))
        files.append(_router_file(model))
    for page in spec.pages:
        files.append(_page_file(page))
    files.append(_readme_file(spec))
    for f in files:
        _validate(f)
    return files


def _validate(f: GeneratedFile) -> None:
    if f.language == "python":
        try:
            ast.parse(f.content, filename=f.path)
        except SyntaxError as exc:
            raise GenerationError(f.path, f"generated Python does not parse: {exc}") from exc
    elif f.language == "javascript":
        opens = f.content.count("{")
        closes = f.content.count("}")
        if opens != closes:
            raise GenerationError(f.path, f"unbalanced braces ({opens} open vs {closes} close)")


