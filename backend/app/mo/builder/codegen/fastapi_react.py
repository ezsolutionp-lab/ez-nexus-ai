"""
MO NEXUS OMEGA — fastapi_react stack generator.

Turns a ProjectSpec into real, syntactically valid source files: SQLAlchemy
models with tenant scoping and soft delete, Pydantic schemas, FastAPI routers
with auth dependencies baked in, a minimal React shell, and an OpenAPI-adjacent
description. This is the only stack in IMPLEMENTED_STACKS (see intent.py) —
claiming another stack works without a generator here is exactly the failure
the directive prohibits.

Every generated file is syntax-checked with `ast.parse` (Python) or a brace/paren
balance check (JS/TS) before it is accepted — a generator bug produces a
BUILD_FAILED result, never a file nobody can compile.
"""

