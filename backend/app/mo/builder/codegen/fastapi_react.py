_SECURITY_PY = '''"""Generated by MO Universal Builder — the secure auth template.

Mirrors the MO Zero Trust model in a standalone application:

  * `secure_router()` builds an APIRouter whose every route already depends on
    an authenticated, tenant-resolved context. A new route is protected because
    of how the router was constructed, not because the author remembered.
  * The tenant comes from the verified token, never from the request body or a
    header a client controls.
  * No secret has a literal default. SECRET_KEY must be set or the app refuses
    to start, so a deployment can never run on a placeholder key.
"""
from __future__ import annotations

import os
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, Request, status
from fastapi.security import OAuth2PasswordBearer
from jose import JWTError, jwt

ALGORITHM = "HS256"
ACCESS_TOKEN_MINUTES = int(os.getenv("ACCESS_TOKEN_MINUTES", "30"))

SECRET_KEY = os.getenv("SECRET_KEY", "")
if not SECRET_KEY:
    raise RuntimeError(
        "SECRET_KEY is not set. Generate one with `python -c \\'import secrets;"
        "print(secrets.token_urlsafe(48))\\'` and set it in the environment. "
        "This application will not start on a placeholder key."
    )

oauth2_scheme = OAuth2PasswordBearer(tokenUrl="/auth/login", auto_error=False)


@dataclass(frozen=True)
class RequestContext:
    """Identity and tenant for one request."""

    tenant_id: str
    actor_id: str
    role: str = "staff"
    scopes: frozenset = field(default_factory=frozenset)

    def require_role(self, *roles: str) -> None:
        if self.role not in roles:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail=f"This action requires one of: {', '.join(roles)}.",
            )


def create_access_token(*, subject: str, tenant_id: str, role: str = "staff") -> str:
    payload = {
        "sub": subject,
        "tenant": tenant_id,
        "role": role,
        "exp": datetime.utcnow() + timedelta(minutes=ACCESS_TOKEN_MINUTES),
    }
    return jwt.encode(payload, SECRET_KEY, algorithm=ALGORITHM)


def resolve_context(
    request: Request,
    token: Optional[str] = Depends(oauth2_scheme),
) -> RequestContext:
    """Authenticate and derive the tenant. Tenant is never client-supplied."""
    if not token:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authentication required.",
            headers={"WWW-Authenticate": "Bearer"},
        )
    try:
        payload = jwt.decode(token, SECRET_KEY, algorithms=[ALGORITHM])
    except JWTError:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Token is invalid or expired.",
            headers={"WWW-Authenticate": "Bearer"},
        )
    tenant_id = payload.get("tenant")
    subject = payload.get("sub")
    if not tenant_id or not subject:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Token is missing claims.")
    return RequestContext(
        tenant_id=tenant_id,
        actor_id=str(subject),
        role=payload.get("role", "staff"),
        scopes=frozenset(payload.get("scopes") or []),
    )


def secure_router(prefix: str, tags: list) -> APIRouter:
    """An APIRouter that is authenticated by construction."""
    return APIRouter(
        prefix=prefix,
        tags=tags,
        dependencies=[Depends(resolve_context)],
        responses={401: {"description": "Authentication required"},
                   403: {"description": "Forbidden"}},
    )
'''

