FIELD_TYPE_TO_SQLALCHEMY = {
    "string": "String(255)", "text": "Text", "integer": "Integer", "float": "Float",
    "boolean": "Boolean", "datetime": "DateTime", "date": "Date", "json": "Text", "enum": "String(40)",
}
FIELD_TYPE_TO_PYDANTIC = {
    "string": "str", "text": "str", "integer": "int", "float": "float",
    "boolean": "bool", "datetime": "datetime", "date": "date", "json": "dict", "enum": "str",
}


@dataclass
class GeneratedFile:
    path: str
    content: str
    language: str

    @property
    def sha256(self) -> str:
        return hashlib.sha256(self.content.encode("utf-8")).hexdigest()

    @property
    def size_bytes(self) -> int:
        return len(self.content.encode("utf-8"))


class GenerationError(Exception):
    def __init__(self, path: str, reason: str):
        super().__init__(f"{path}: {reason}")
        self.path = path
        self.reason = reason


def _pascal(name: str) -> str:
    return "".join(w.capitalize() for w in name.replace("-", "_").split("_"))


def _model_file(model: ModelSpec) -> GeneratedFile:
    lines = [
        '"""Generated by MO Universal Builder. Edit through the Builder, not by hand,',
        "or mark your change CUSTOM_CODE so round-trip generation preserves it.",
        '"""',
        "from __future__ import annotations",
        "from datetime import datetime",
        "from sqlalchemy import Boolean, Column, Date, DateTime, Float, Integer, String, Text",
        "from sqlalchemy.orm import relationship",
        "from app.database import Base",
        "",
        "",
        f"class {model.name}(Base):",
        f'    """{model.description}"""',
        "",
        f'    __tablename__ = "{model.table}"',
        "",
        "    id = Column(Integer, primary_key=True, index=True)",
        '    tenant_id = Column(String(64), nullable=False, index=True)' if model.tenant_scoped else "    # not tenant-scoped",
    ]
    for f in model.fields:
        col = FIELD_TYPE_TO_SQLALCHEMY[f.type]
        args = [col]
        if f.required:
            args.append("nullable=False")
        else:
            args.append("nullable=True")
        if f.unique:
            args.append("unique=True")
        if f.indexed:
            args.append("index=True")
        if f.default is not None:
            args.append(f"default={f.default!r}")
        lines.append(f"    {f.name} = Column({', '.join(args)})")
    lines.append("    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)")
    lines.append("    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow, nullable=False)")
    lines.append('    is_deleted = Column(Boolean, default=False, nullable=False)   # soft delete')
    lines.append("")
    return GeneratedFile(f"app/models/{model.table}.py", "\n".join(lines) + "\n", "python")


def _schema_file(model: ModelSpec) -> GeneratedFile:
    lines = [
        '"""Generated by MO Universal Builder."""',
        "from __future__ import annotations",
        "from datetime import datetime, date",
        "from typing import Optional",
        "from pydantic import BaseModel, ConfigDict",
        "",
        "",
        f"class {model.name}Base(BaseModel):",
    ]
    for f in model.fields:
        py_type = FIELD_TYPE_TO_PYDANTIC[f.type]
        annotation = py_type if f.required else f"Optional[{py_type}]"
        default = "" if f.required else f" = {f.default!r}" if f.default is not None else " = None"
        lines.append(f"    {f.name}: {annotation}{default}")
    if not model.fields:
        lines.append("    pass")
    lines += [
        "",
        "",
        f"class {model.name}Create({model.name}Base):",
        "    pass",
        "",
        "",
        f"class {model.name}Update(BaseModel):",
    ]
    for f in model.fields:
        py_type = FIELD_TYPE_TO_PYDANTIC[f.type]
        lines.append(f"    {f.name}: Optional[{py_type}] = None")
    if not model.fields:
        lines.append("    pass")
    lines += [
        "",
        "",
        f"class {model.name}Out({model.name}Base):",
        "    model_config = ConfigDict(from_attributes=True)",
        "    id: int",
        "    created_at: datetime",
        "",
    ]
    return GeneratedFile(f"app/schemas/{model.table}.py", "\n".join(lines) + "\n", "python")


