def _page_file(page: PageSpec) -> GeneratedFile:
    component = _pascal(page.name) + "Page"
    sections = "\n".join(f'      <section id="{s}" className="mo-section" />' for s in page.sections)
    content = _PAGE_TEMPLATE.format(component=component, kind=page.kind, title=page.title, sections=sections)
